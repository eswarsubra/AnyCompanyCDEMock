"""Render an :class:`~evaluation.harness.EvaluationResult` into Markdown.

Pure formatting — no I/O, no AWS — so it is trivially unit-tested. The CLI
(``run_evaluation``) writes the returned string to
``evaluation/reports/quality-report.md``.
"""
from __future__ import annotations

from typing import Optional

from evaluation.harness import EvaluationResult


def _fmt(value: Optional[float]) -> str:
    """Render an optional numeric metric, using an en dash for missing values."""
    return "–" if value is None else f"{value:g}"


def render_markdown(result: EvaluationResult, *, generated_at: str) -> str:
    """Render the evaluation result as a Markdown quality report.

    Args:
        result: the aggregated evaluation outcome.
        generated_at: an ISO-8601 timestamp string (passed in so this function
            stays pure and its output is deterministic for tests).

    Returns:
        The full Markdown document as a string.
    """
    lines = []
    lines.append("# Translation quality report")
    lines.append("")
    lines.append(
        "Generated by the evaluation harness (`evaluation/`). Measures AI-output "
        "quality over the review dataset using two independent signals: an "
        "LLM-as-judge fidelity/fluency score (the pipeline's own Bedrock quality "
        "stage) and a back-translation round-trip similarity score."
    )
    lines.append("")
    lines.append(f"- **Generated at:** {generated_at}")
    lines.append(f"- **Reviews evaluated:** {result.total_reviews}")
    lines.append(
        f"- **Reviews translated:** {result.translated_reviews} "
        f"(the rest are source-language passthrough)"
    )
    lines.append(f"- **Translations scored:** {result.total_translations}")
    lines.append(
        f"- **Target languages:** {', '.join(result.target_languages)}"
    )
    lines.append(
        f"- **Judge scale:** {_fmt(result.scale_min)}–{_fmt(result.scale_max)}; "
        f"**keep threshold:** {_fmt(result.quality_threshold)} "
        f"(a translation is *kept* when its judge score ≥ threshold)"
    )
    lines.append("")

    # --- Per-language table ------------------------------------------------
    lines.append("## Per-language quality")
    lines.append("")
    lines.append(
        "| Language | Translations | Mean judge score | Mean back-translation "
        "similarity | Kept | Filtered | % kept |"
    )
    lines.append("|---|---:|---:|---:|---:|---:|---:|")
    for lang in result.target_languages:
        metrics = result.per_language.get(lang)
        if metrics is None:
            continue
        lines.append(
            f"| {lang} | {metrics.translation_count} | "
            f"{_fmt(metrics.mean_judge_score)} | {_fmt(metrics.mean_similarity)} | "
            f"{metrics.kept_count} | {metrics.filtered_count} | "
            f"{metrics.kept_pct:g}% |"
        )
    lines.append("")

    # --- Overall -----------------------------------------------------------
    lines.append("## Overall")
    lines.append("")
    lines.append(f"- **Kept:** {result.overall_kept} / {result.total_translations} "
                 f"({result.overall_kept_pct:g}%)")
    lines.append(f"- **Filtered (below threshold):** {result.overall_filtered}")
    lines.append("")

    # --- How to read -------------------------------------------------------
    lines.append("## How to read this report")
    lines.append("")
    lines.append(
        "- **Mean judge score** is the pipeline's own fidelity+fluency rating "
        "(same prompt/model/threshold the deployed quality stage uses). Higher "
        "is better; translations below the keep threshold are filtered before "
        "the API serves them."
    )
    lines.append(
        "- **Mean back-translation similarity** (0–1) round-trips each "
        "translation back to its source language and lexically compares it to "
        "the original. It is an independent, deterministic sanity check: a low "
        "value flags a translation whose meaning did not survive the round trip."
    )
    lines.append(
        "- **% kept** is the share of translations at or above the keep "
        "threshold — the conversion-relevant signal for how much translated "
        "content actually reaches the product page."
    )
    lines.append("")
    lines.append(
        "_Re-run with_ `python -m evaluation.run_evaluation` _(see the "
        "README Evaluation section) to regenerate this report._"
    )
    lines.append("")
    return "\n".join(lines)
